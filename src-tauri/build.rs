///
/// Naming them here is the whole reason the capability files bind at all.
/// `tauri-2.11.5` only runs an app command through the ACL when
/// `plugin_command.is_some() || has_app_acl_manifest || !is_local`
/// (`src/webview/mod.rs:1823`). Both Butterfly Speak windows load local URLs and
/// there was no app manifest, so until this list existed *every* command below
/// was invokable from the overlay — a transparent, click-through pill — with
/// nothing in `capabilities/` mentioning it.
///
/// `AppManifest::commands` writes an `allow-<command>`/`deny-<command>` pair per
/// entry into `permissions/autogenerated/` (`tauri-build-2.6.3/src/acl.rs:278`,
/// `tauri-utils-2.9.3/src/acl/build.rs:255`), and the app manifest that produces
/// is what flips `has_app_acl_manifest` (`tauri-build-2.6.3/src/acl.rs:408`).
/// That switch is all-or-nothing and app-wide: the moment one app permission
/// exists, every command is deny-by-default in *both* windows. So this list and
/// `capabilities/main.json` have to be added to together — a command registered
/// in `generate_handler!` but missing from either one is silently rejected at
/// runtime with "not allowed by ACL", not a compile error. The `capability_split`
/// tests in `src/lib.rs` are what turn that into a compile-time-ish failure.
///
