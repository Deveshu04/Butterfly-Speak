/// Delete `permissions/autogenerated/*.toml` for commands that are no longer in
/// `COMMANDS`.
///
/// `autogenerate_command_permissions` only ever writes
/// (`tauri-utils-2.9.3/src/acl/build.rs:307`); nothing removes the file for a
/// command that has since been renamed or deleted. The directory is gitignored
/// build output, so a branch switch does not clean it either, and
/// `app_manifest_permissions` then re-reads the whole of `permissions/**/*`
/// (`tauri-build-2.6.3/src/acl.rs:315-328`). The result is that a deleted
/// command's `allow-<gone>` survives on disk and stays a valid, grantable
/// permission — `validate_capabilities` keeps passing for a capability naming a
/// command the app no longer has. That is precisely the drift `capability_split`
/// exists to catch, and it is the one direction those tests cannot see, because
/// they read the three source files and never the generated set.
///
/// Only strays are removed, never rewritten: `write_if_changed` leaves current
/// files untouched, so in the ordinary case this touches nothing and the
/// `cargo:rerun-if-changed=permissions` instruction does not fire a rebuild.
fn prune_stale_permissions() {
    let dir = std::path::Path::new("permissions/autogenerated");
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        let current = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .is_some_and(|stem| COMMANDS.contains(&stem));
        if !current {
            println!(
                "cargo:warning=removing stale app permission {} (no such command)",
                path.display()
            );
            let _ = std::fs::remove_file(&path);
        }
    }
}

fn main() {
    prune_stale_permissions();
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(COMMANDS)),
    )
    .expect("tauri-build failed");
}
