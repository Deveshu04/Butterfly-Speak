#!/usr/bin/env python3
"""fetch_corpora.py -- downloads, converts, and samples the formatting-eval
corpus fixtures committed under tests/fixtures/*.jsonl.

Methodology (AssemblyAI's Universal-2-TF, arXiv:2501.05948): take text that
ALREADY has correct punctuation and casing, strip it to lowercase and
unpunctuated to simulate raw ASR output, then measure how well the
formatter restores it. No individual's writing preferences enter this --
every fixture line is `input` (simulated raw ASR) paired with `target`
(the ground truth it should restore to), one JSON object per line:

    {"id":..., "source":..., "kind":"punctuation"|"disfluency", "lang":...,
     "input":..., "target":..., "verbatim": optional, "tags": optional}

Run it from the repo root with no arguments. It needs only the Python 3
standard library: every source fetched below is JSON or pipe-delimited text.

    python tools/fetch_corpora.py

It downloads each source's real upstream data (full sets -- that IS the "on
demand" fetch), converts it to the fixture schema above, deterministically
samples ~200 cases per source (SAMPLE_SEED below, so re-running reproduces
the same commit-sized sample), and writes:

    tests/fixtures/<source>.jsonl   -- one file per source, ~200 lines
    tests/fixtures/LICENSE.md       -- generated attribution block, for humans
    tests/fixtures/sources.json     -- the same metadata, for the harness

Raw downloads are cached under tools/.cache/ (gitignored) so re-runs don't
re-fetch multi-megabyte archives.

------------------------------------------------------------------------
WHAT GETS WRITTEN UNDER tests/fixtures/, AND WHAT GATES IT
------------------------------------------------------------------------
Three functions write under `tests/fixtures/`, and only one of them writes
corpus DATA:

  * `write_fixture()` -- the only writer of `*.jsonl` case data. It refuses
    (raises, writes nothing) unless the `source_key` is a key of `SOURCES`
    below AND the license recorded for it is in `ALLOWED_LICENSES`. There
    is no argument, flag, or environment variable that bypasses either
    check.
  * `write_license_md()` and `write_sources_json()` -- generated metadata.
    Neither writes case data; both just serialize the `SOURCES` table, so
    neither can introduce a source `write_fixture` would have refused.

THE GATE IS ON THE LICENSE, NOT ON THE KEY. Adding a row to `SOURCES` is
not by itself permission to ship it: `ALLOWED_LICENSES` is the whitelist,
and a source carrying anything else -- CC BY-NC, CC BY-ND, an LDC
agreement, no license at all -- is refused at import time and again at
write time, however impeccable its key looks. This is deliberate: the
failure mode being defended against is a contributor adding a
well-described non-commercial source and everything downstream quietly
recording "CC BY-NC 4.0" as though that were fine.

Every source actually committed here was license-verified against a
FIRST-PARTY statement found at fetch time (a LICENSE file shipped in the
source's own distribution, or a `license` field in its own dataset card),
not merely trusted from whatever named it. See `PENDING_SOURCES` and
`BLOCKED_SOURCES` below for sources that were investigated and are
DELIBERATELY not in `SOURCES`, and why -- DISCO is named as CC BY 4.0, but
that verification step turned up no license grant for its data.
`tests/fixtures/LICENSE.md` (generated by this script) repeats all of this
for a reader who never opens the source code.

Never commit TED-LIUM, MuST-C, IWSLT, SponSpeech, Switchboard, or Fisher
material -- all are CC BY-NC / CC BY-NC-ND or LDC-paid. Never commit
Svarah, IndicVoices, IndicVoices-R, Kathbath, Shrutilipi, or AI4Bharat's
NPTEL2020 either -- empirically punctuation-stripped (Svarah also has no
stated license anywhere), so even leaving licensing aside they cannot
measure what a formatting-restoration fixture claims to measure. See
`BLOCKED_SOURCES`.

------------------------------------------------------------------------
UPSTREAM REVISIONS ARE PINNED
------------------------------------------------------------------------
Each source records the exact upstream revision its fixture was built
from (`revision` in `SOURCES`): a git commit SHA for the GitHub sources, a
repo SHA for the Hugging Face one, a SHA-256 of the archive for
LibriSpeech-PC, which is served from a plain mirror with no revisions at
all. Every fetch either requests that exact revision or verifies it after
the fact and raises. Re-running therefore reproduces byte-identical
fixtures, or fails loudly -- it cannot silently produce different data
because upstream moved.
"""

