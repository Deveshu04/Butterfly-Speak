_DIARBENCH_ROWS_URL = (
    "https://datasets-server.huggingface.co/rows"
    "?dataset=sarvamai%2Findic-diarbench&config=Hindi&split=test"
    "&offset={offset}&length={length}"
)

_DIARBENCH_REPO_API = "https://huggingface.co/api/datasets/sarvamai/indic-diarbench"

_NONSPEECH_TAG_RE = re.compile(r"^\s*<[^<>]+>\s*$")
_PAGE_LENGTH = 20
# Enough rows to comfortably clear TARGET_SAMPLE_SIZE valid segments without
# pulling all 94 available test rows (or their audio-URL metadata) on every
# run; raise if the source's segment density ever drops.
_MAX_ROWS = 60

# This benchmark's gloss convention: a Devanagari-spelled word followed by
# its Latin-script or numeric form in parentheses --
# "इंटरव्यू(interview)", "आई-क्यू(IQ)", "सात-आठ(7-8)", "तीस(30)".
# Matches a parenthesised run that contains an ASCII letter or digit and NO
# Devanagari, so an ordinary Devanagari parenthetical aside (were one to
# appear) is not mistaken for a gloss. The digit-only form
# ("तीस(30)") is included deliberately: it is the same convention and the
# same scoring problem -- the formatter would have to invent "(30)" out of
# the spelled-out word -- and excluding it would leave a handful of cases
# carrying the artifact untagged.
_ENGLISH_GLOSS_RE = re.compile(r"\([^()ऀ-ॿ]*[A-Za-z0-9][^()ऀ-ॿ]*\)")


def _diarbench_gloss_tags(target):
    """Tags marking the parenthesised-English-gloss annotation artifact.

    `strip_to_raw` removes parentheses along with every other punctuation
    mark, so a fixture built from this source scores the formatter on
    putting them back -- i.e. on reproducing a transcription convention,
    not on any formatting behaviour a dictation user would notice. That is
    a real property of the data and it is the majority of the punctuation
    in it, so the cases carry it explicitly instead of a report having to
    rediscover it. See this source's `caveat` for the measured share.
    """
    tags = []
    if _ENGLISH_GLOSS_RE.search(target):
        tags.append("english-gloss")
        marks = [
            ch
            for ch in target
            if unicodedata.category(ch).startswith("P") and ch not in _KEEP_PUNCT
        ]
        parens = sum(1 for ch in marks if ch in "()")
        if marks and parens / len(marks) >= 0.5:
            tags.append("gloss-dominated")
    return tags


def fetch_indic_diarbench():
    # The datasets-server /rows endpoint takes no revision parameter, so
    # the pin is verified against the repo API instead: if upstream has
    # moved, this raises rather than quietly building different fixtures.
    repo = http_get_json(_DIARBENCH_REPO_API, cache_name="diarbench-repo.json")
    if repo.get("sha") != _DIARBENCH_REVISION:
        raise RuntimeError(
            f"indic-diarbench: repo is now at {repo.get('sha')!r}, fixtures "
            f"were built from {_DIARBENCH_REVISION!r}. Bump "
            f"_DIARBENCH_REVISION only after reviewing the fixture diff a "
            f"re-run produces."
        )
    # Same check for the license: the dataset card is the first-party
    # evidence, and a card can be edited.
    card_license = (repo.get("cardData") or {}).get("license")
    if card_license != "cc-by-4.0":
        raise RuntimeError(
            f"indic-diarbench: dataset card now says license={card_license!r}, "
            f"expected 'cc-by-4.0' (the first-party evidence this source is "
            f"admitted on). Refusing to build a fixture from it."
        )

    cases = []
    offset = 0
    while offset < _MAX_ROWS and len(cases) < TARGET_SAMPLE_SIZE * 3:
        url = _DIARBENCH_ROWS_URL.format(offset=offset, length=_PAGE_LENGTH)
        page = http_get_json(url, cache_name=f"diarbench-hi-{offset:03d}.json")
        rows = page.get("rows", [])
        if not rows:
            break
        for row in rows:
            for seg in row["row"]["annotated_transcript"]:
                transcript = (seg.get("transcript") or "").strip()
                if not transcript or _NONSPEECH_TAG_RE.match(transcript):
                    continue
                # Drop inline non-speech tags but keep the surrounding
                # speech ("...<noise> ..." segments do occur).
                cleaned = re.sub(r"<[^<>]+>", " ", transcript)
                cleaned = re.sub(r"\s+", " ", cleaned, flags=re.UNICODE).strip()
                if len(cleaned) < 6:
                    continue
                raw_input = strip_to_raw(cleaned)
                if not raw_input:
                    continue
                cases.append(
                    {
                        "id": f"diarbench-hi-{len(cases):04d}",
                        "source": "indic-diarbench",
                        "kind": "punctuation",
                        "lang": "hi",
                        "input": raw_input,
                        "target": cleaned,
                        "tags": _diarbench_gloss_tags(cleaned),
                    }
                )
        offset += _PAGE_LENGTH
        if not page.get("rows") or offset >= page.get("num_rows_total", offset):
            break
    return cases


