# The published test.json contains 13 pairs (out of 3643) where "disfluent"
# is literally the string "#VALUE!" -- a spreadsheet formula-error artifact
# baked into the upstream data (evidently produced through Excel/Sheets at
# some point in Disfl-QA's own pipeline), not something this script
# introduces. Confirmed by scanning the raw file directly. A handful of
# other Excel error tokens are guarded defensively even though only
# "#VALUE!" was observed, since the failure mode (a formula literal leaking
# into a text column) is generic to whatever produced this one.
_EXCEL_ERROR_RE = re.compile(r"^#(VALUE|REF|DIV/0|NAME|NULL|NUM|N/A)[!?]?$")


def fetch_disflqa():
    data = http_get_json(_DISFLQA_TEST, cache_name="disflqa-test.json")
    cases = []
    skipped_excel_errors = 0
    for i, (_qid, pair) in enumerate(sorted(data.items())):
        original = pair["original"].strip()
        disfluent = pair["disfluent"].strip()
        if not original or not disfluent:
            continue
        if _EXCEL_ERROR_RE.match(original) or _EXCEL_ERROR_RE.match(disfluent):
            skipped_excel_errors += 1
            continue
        raw_input = strip_to_raw(disfluent)
        if not raw_input:
            continue
        cases.append(
            {
                "id": f"disflqa-test-{i:04d}",
                "source": "disflqa",
                "kind": "disfluency",
                "lang": "en",
                "input": raw_input,
                "target": original,
                "verbatim": disfluent,
            }
        )
    if skipped_excel_errors:
        print(f"disflqa: skipped {skipped_excel_errors} '#VALUE!'-poisoned rows")
    return cases


