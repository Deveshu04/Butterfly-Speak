def _parse_nlp_rows(nlp_text):
    """Rev's `.nlp` format: a pipe-delimited header line
    (token|speaker|ts|endTs|punctuation|prepunctuation|case|tags) then one
    row per token. Rows whose field count disagrees with the header, and
    rows with an empty token, are dropped."""
    lines = nlp_text.splitlines()
    header = lines[0].split("|")
    rows = []
    for line in lines[1:]:
        if not line:
            continue
        fields = line.split("|")
        if len(fields) != len(header):
            continue
        row = dict(zip(header, fields))
        if not row.get("token"):
            continue
        rows.append(row)
    return rows


def _render_nlp_rows(rows):
    return " ".join(
        (r.get("prepunctuation") or "") + r["token"] + (r.get("punctuation") or "")
        for r in rows
    )


def _reconstruct_earnings22_text(nlp_text):
    return _render_nlp_rows(_parse_nlp_rows(nlp_text))


