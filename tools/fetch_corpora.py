# Rev marks a false start / cut-off word with a trailing hyphen: "curren-",
# "re-", "aco-". Verified against the shipped transcripts.
_FALSE_START_RE = re.compile(r"[-–—]$")

# A token carrying an annotation rather than speech.
_NLP_ANNOTATION_RE = re.compile(r"[<>\[\]]")

# Sentence-final punctuation after these is an abbreviation's period, not a
# sentence boundary, so it must not become a cut point ("...introduce you to
# Mr. Sean" would otherwise be cut after "Mr."). Only tokens that are
# essentially always abbreviations: "No." is deliberately absent, because in
# this corpus "no." far more often ends a sentence than numbers one.
_ABBREVIATIONS = frozenset(
    {
        "mr",
        "mrs",
        "ms",
        "dr",
        "prof",
        "sr",
        "jr",
        "st",
        "inc",
        "ltd",
        "co",
        "corp",
        "vs",
        "etc",
        "approx",
    }
)


def _nlp_word(token):
    """Comparison key for aligning the two transcript styles: case- and
    punctuation-insensitive, so the alignment sees word identity only and
    a restyled capital or a moved comma is not mistaken for a word change.
    Surface differences are checked separately, and rejected."""
    return re.sub(r"[^\w']", "", token.lower(), flags=re.UNICODE)


def _render_row(row):
    """One `.nlp` row as it appears in the rendered text -- the same
    concatenation `_render_nlp_rows` performs, for a single row."""
    return (row.get("prepunctuation") or "") + row["token"] + (row.get("punctuation") or "")


def _is_subsequence(needle, haystack):
    """True iff `needle` can be obtained from `haystack` by deleting
    characters and nothing else. Greedy left-to-right matching, which is
    exact for subsequence testing (the earliest match always leaves the
    longest remaining haystack)."""
    it = iter(haystack)
    return all(ch in it for ch in needle)


def _ends_sentence(row):
    token = _nlp_word(row["token"])
    if token in _ABBREVIATIONS:
        return False
    return bool(re.search(r"[.?!]", row.get("punctuation") or ""))


def _classify_removal(verbatim_rows, i1, i2):
    """Why were `verbatim_rows[i1:i2]` dropped from the non-verbatim style?

    Returns a sorted list of reasons -- some subset of {"filler",
    "repetition", "false-start"} -- or None if any removed token cannot be
    explained by one of them.

    None is the important case. Rev's transcriptionists also reworded for
    readability ("gonna" -> "going to"), dropped ordinary articles, and
    fixed mishearings. Those are editorial judgements about someone else's
    speech; a dictation formatter neither can nor should reproduce them,
    and a fixture that demanded it would cap the achievable score at
    something meaningless. Anything unexplained here means the whole unit
    is discarded.
    """
    removed = [_nlp_word(r["token"]) for r in verbatim_rows[i1:i2]]
    span = i2 - i1
    if not removed:
        return None

    # Whole-span immediate repetition: "on the, on the chart" (the span
    # repeats what directly follows) or "are, are, are looking" (it repeats
    # what directly precedes).
    following = [_nlp_word(r["token"]) for r in verbatim_rows[i2 : i2 + span]]
    preceding = [_nlp_word(r["token"]) for r in verbatim_rows[max(0, i1 - span) : i1]]
    if removed in (following, preceding):
        return ["repetition"]

    # Per-token fallback. A removed word counts as a repetition only when
    # the copy it duplicates SURVIVES -- these two are the surviving
    # neighbours of the whole removed run (difflib emits maximal runs, so
    # the rows either side of a `delete` are not themselves deleted).
    #
    # Comparing a removed token against its removed NEIGHBOURS would call
    # an outright word deletion a repetition: "in the the chart" -> "in
    # chart" removes BOTH copies of "the", and each copy would then "match"
    # the other. Nothing is de-duplicated there; the transcriptionist
    # dropped the word, which is an editorial edit and belongs in the
    # discard pile with the rest. The surviving-copy rule also stops
    # under-counting in the other direction: in "the, uh, the chart" ->
    # "the chart" the removed "the" duplicates the surviving "the" across
    # the intervening filler, which a neighbour-of-a-neighbour walk cannot
    # see.
    before = _nlp_word(verbatim_rows[i1 - 1]["token"]) if i1 else None
    after = _nlp_word(verbatim_rows[i2]["token"]) if i2 < len(verbatim_rows) else None

    reasons = set()
    for row in verbatim_rows[i1:i2]:
        word = _nlp_word(row["token"])
        if word in _FILLER_TOKENS:
            reasons.add("filler")
            continue
        if _FALSE_START_RE.search(row["token"]):
            reasons.add("false-start")
            continue
        if word and word in (before, after):
            reasons.add("repetition")
            continue
        return None
    return sorted(reasons) if reasons else None


def _subset10_units(verbatim_rows, nonverbatim_rows, stats=None):
    """Yields (verbatim_slice, nonverbatim_slice, reasons) for every
    sentence-level unit where the non-verbatim style is the verbatim style
    with disfluencies deleted and nothing else changed.

    Upstream ships no alignment between the two styles -- just two token
    streams for the same audio -- so one is derived here: align on word
    identity, cut only where BOTH sides end a sentence at the same aligned
    token (an unambiguous shared boundary), then keep a unit only if every
    edit inside it is an explained deletion.

    THE INVARIANT, STATED EXACTLY, because everything downstream leans on
    it: the non-verbatim unit is the verbatim unit with WHOLE TOKENS
    deleted and, on each token that survives, PUNCTUATION CHARACTERS
    deleted -- nothing inserted, nothing substituted, nothing re-cased,
    anywhere, punctuation included. Punctuation deletion has to be allowed
    because it is a mechanical consequence of the token deletion: the
    commas in "So, obviously higher margins, uh, excluding those sales."
    exist only to set off the filler, and requiring the clean side to keep
    them would make the TARGETS worse ("...margins, excluding..."), not the
    filter stricter. Punctuation ADDITION and SUBSTITUTION are a different
    thing entirely and are rejected: "So" -> "So," inserts a judgement the
    verbatim never made, "detail." -> "detail?" reinterprets the sentence,
    and "CapEx. Um, our guidance" -> "CapEx, our guidance" merges two
    sentences into one. Those are editorial rewrites, and they are what
    this filter exists to keep out. Without the punctuation half of the
    check they go straight through: measured on a sample built without it,
    43 of 200 cases add or swap punctuation on a surviving token, and none
    of those 43 fails the casing half -- so punctuation is the entire gap,
    not part of it.
    """
    a = [_nlp_word(r["token"]) for r in verbatim_rows]
    b = [_nlp_word(r["token"]) for r in nonverbatim_rows]
    opcodes = difflib.SequenceMatcher(a=a, b=b, autojunk=False).get_opcodes()

    cuts = [(0, 0)]
    for tag, i1, _i2, j1, j2 in opcodes:
        if tag != "equal":
            continue
        for offset in range(j2 - j1):
            if _ends_sentence(verbatim_rows[i1 + offset]) and _ends_sentence(
                nonverbatim_rows[j1 + offset]
            ):
                cuts.append((i1 + offset + 1, j1 + offset + 1))
    cuts.append((len(verbatim_rows), len(nonverbatim_rows)))

    for (i_start, j_start), (i_end, j_end) in zip(cuts, cuts[1:]):
        v_slice = verbatim_rows[i_start:i_end]
        n_slice = nonverbatim_rows[j_start:j_end]
        # Counted before every filter, length gate included, so the survival
        # rate this script prints (and the caveat quotes) has one obvious
        # denominator -- every sentence-level unit the shared-boundary cut
        # produced -- and is measured on each run rather than copied
        # forward from an older one.
        if stats is not None:
            stats["candidates"] = stats.get("candidates", 0) + 1
        if not (4 <= len(v_slice) <= 40) or len(n_slice) < 3:
            continue

        reasons = set()
        removed_tokens = 0
        ok = True
        for tag, i1, i2, j1, j2 in opcodes:
            if tag == "insert":
                # An `insert` consumes nothing on the verbatim side
                # (i1 == i2), so its verbatim index says only WHERE it sits,
                # never whether its tokens land in this unit. The question
                # that matters is on the non-verbatim side: do any of the
                # inserted rows fall inside nonverbatim_rows[j_start:j_end],
                # i.e. inside the text that becomes this unit's `target`? If
                # so the target contains a word the verbatim never had, and
                # the unit is out.
                #
                # A strict `i_start < i1 < i_end` test would miss an
                # insertion anchored exactly at the unit's LEADING boundary
                # (i1 == i_start), though its tokens sit at the front of
                # this unit's target.
                if j1 < j_end and j2 > j_start:
                    ok = False
                    break
                continue
            if i2 <= i_start or i1 >= i_end:
                continue
            if tag == "replace":
                ok = False
                break
            if tag == "delete":
                why = _classify_removal(verbatim_rows, i1, i2)
                if why is None:
                    ok = False
                    break
                reasons.update(why)
                removed_tokens += i2 - i1
        if not ok or removed_tokens == 0:
            continue

        # Every surviving token, checked on its FULL rendered surface --
        # prepunctuation + token + punctuation -- not just the word.
        #
        #   * the word itself must be byte-identical, casing included. Rev's
        #     two styles differ on things like "Regional Brands" vs
        #     "regional brands" and "Covid" vs "COVID"; that is house style,
        #     not disfluency, and scoring it here would smuggle a
        #     capitalization judgement into a disfluency metric.
        #   * the rendered surface must be a SUBSEQUENCE of the verbatim
        #     one, so punctuation may only disappear. Anything added,
        #     moved onto this token, or swapped for a different mark fails.
        #
        # The second half is needed because `punctuation` is a separate
        # `.nlp` column: a check on `row["token"]` alone would not see
        # any punctuation edit the transcriptionist made.
        #
        # Because the survivors are walked in order and inserts/replaces
        # are already rejected, this pairwise property implies the whole
        # unit's rendered text is a character-subsequence of the verbatim
        # unit's -- i.e. deletion-only holds for the unit, not just
        # token-by-token. The pairwise form is the stronger of the two and
        # is the one enforced: checking only the whole unit lets a mark
        # freed by a deletion re-appear somewhere else and still match, and
        # that is exactly how "CapEx. Um, our guidance" -> "CapEx, our
        # guidance" (a sentence merge) sneaks past.
        drift = False
        for tag, i1, i2, j1, _j2 in opcodes:
            if tag != "equal":
                continue
            for i in range(max(i1, i_start), min(i2, i_end)):
                v_row = verbatim_rows[i]
                n_row = nonverbatim_rows[j1 + (i - i1)]
                if v_row["token"] != n_row["token"] or not _is_subsequence(
                    _render_row(n_row), _render_row(v_row)
                ):
                    drift = True
                    break
            if drift:
                break
        if drift:
            continue

        yield v_slice, n_slice, sorted(reasons)


