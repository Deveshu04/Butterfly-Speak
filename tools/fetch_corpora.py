FETCHERS = {
    "librispeech-pc": fetch_librispeech_pc,
    "earnings22": fetch_earnings22,
    "earnings22-subset10": fetch_earnings22_subset10,
    "disflqa": fetch_disflqa,
    "indic-diarbench": fetch_indic_diarbench,
}


def _demonstrate_refusals():
    """Run the two refusals for real, BEFORE anything is fetched or written.

    Not mocked and not hypothetical: `main()` calls this first, so if either
    gate has stopped refusing, the script aborts having written nothing.
    Run at the END of `main()`, after every fixture had been written to
    disk, an "abort" would stop nothing, because the files the broken gate
    let through would already be sitting in `tests/fixtures/` for the next
    `git add`. Order is the whole mechanism here, not a detail.
    """
    # 1. A source investigated and deliberately not shipped (DISCO).
    try:
        write_fixture("disco", [{"id": "should-not-be-written"}])
    except ValueError as e:
        print(f"allow-list correctly refused 'disco': {e}")
    else:
        raise AssertionError("write_fixture('disco', ...) should have refused")

    # 2. The case that actually matters: a source WITH a SOURCES entry, a
    # plausible name, and a genuine first-party license -- that happens to
    # be non-commercial. Gating the key would let this through; gating the
    # license does not. Injected and removed here so the check runs against
    # the real write path rather than a copy of its logic.
    probe_key = "__license-gate-probe__"
    assert probe_key not in SOURCES
    SOURCES[probe_key] = {
        "name": "License gate probe",
        "url": "https://example.invalid/",
        "license": "CC BY-NC 4.0",
        "license_url": "https://creativecommons.org/licenses/by-nc/4.0/",
        "license_evidence": "n/a -- this row exists only to be refused",
        "citation": "n/a",
        "caveat": "n/a",
        "revision": "n/a",
        "revision_kind": "n/a",
    }
    try:
        write_fixture(probe_key, [{"id": "should-not-be-written"}])
    except ValueError as e:
        print(f"license gate correctly refused a CC BY-NC source: {e}")
    else:
        raise AssertionError(
            "write_fixture on a CC BY-NC source should have refused -- the "
            "gate is on the license, and it is not holding"
        )
    finally:
        del SOURCES[probe_key]
    assert not (FIXTURES_DIR / f"{probe_key}.jsonl").exists()


def main():
    assert set(FETCHERS) == ALLOWED_SOURCES, "every allowed source needs a fetcher"

    # FIRST, before a byte is fetched or written. An allow-list check that
    # runs after the fixtures are on disk cannot prevent anything; this one
    # aborts the run with nothing written.
    _demonstrate_refusals()

    failures = []
    sampled_by_source = {}
    for key, fetch in FETCHERS.items():
        print(f"--- {key} ---")
        try:
            raw_cases = fetch()
            sampled = sample_cases(raw_cases)
            print(f"{key}: {len(raw_cases)} candidates, sampling {len(sampled)}")
            write_fixture(key, sampled)
            sampled_by_source[key] = sampled
        except Exception as e:  # noqa: BLE001 -- report and keep going
            print(f"{key}: FAILED: {e}", file=sys.stderr)
            failures.append(key)

    write_license_md({k: len(v) for k, v in sampled_by_source.items()})
    write_sources_json(sampled_by_source)

    if failures:
        print(f"FAILED sources: {failures}", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
