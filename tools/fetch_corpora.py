# Word-internal characters that stay glued to their word instead of being
# treated as restorable punctuation -- the same choice eval::per's own
# tokenizer makes for hyphens and quotes (see its module doc: "Every other
# character -- hyphen, quote, dash, combining mark -- is glued into the
# current word rather than dropped").
_KEEP_PUNCT = {"'", "-"}


def strip_to_raw(text):
    """Simulates raw, lowercase, unpunctuated ASR output from text that is
    already correctly cased and punctuated -- the strip-and-restore half of
    the AssemblyAI Universal-2-TF methodology this whole corpus is built on.

    Removes every character in Unicode general category P* (periods,
    commas, question/exclamation marks, quotes, brackets, em/en dashes,
    ellipses, and the Devanagari danda/double danda ।॥ alike), except
    the ASCII apostrophe and hyphen-minus, which are left glued to their
    word (see `_KEEP_PUNCT`). A removed character becomes a space, not
    nothing, so words never fuse across it: "well-known," -> "well-known"
    keeps the hyphen, drops the comma, and still has a word boundary where
    the comma was.

    Uses `unicodedata.category()`, not a `\\w`-based regex, on purpose:
    Python's `\\w` excludes the Unicode combining-mark categories Mn/Mc that
    Devanagari vowel signs and the virama are made of, so an allow-list
    regex shatters matra-bearing words -- see per_oracle.py's docstring and
    eval/per.rs's module doc for the identical trap in this repo's other
    Python/Rust pair. A punctuation-category DENYLIST never touches a
    combining mark, so it cannot make that mistake, and it is exactly the
    boundary this corpus needs: strip marks, keep every letter whole.
    """
    out = []
    for ch in text:
        if ch in _KEEP_PUNCT:
            out.append(ch)
        elif unicodedata.category(ch).startswith("P"):
            out.append(" ")
        else:
            out.append(ch)
    return re.sub(r"\s+", " ", "".join(out), flags=re.UNICODE).strip().lower()


def sample_cases(cases, n=TARGET_SAMPLE_SIZE, seed=SAMPLE_SEED):
    """Deterministic sample of up to `n` cases, order-independent of the
    input list's order (sorted by id first) so re-runs are reproducible
    even if an upstream source reorders rows between fetches."""
    ordered = sorted(cases, key=lambda c: c["id"])
    if len(ordered) <= n:
        return ordered
    rng = random.Random(seed)
    return sorted(rng.sample(ordered, n), key=lambda c: c["id"])


def http_get(url, cache_name=None):
    """GET `url`, using tools/.cache/<cache_name> as a read-through cache
    when given. Raises with the URL in the message on any failure -- a
    fixture silently built from a truncated/failed download is worse than
    this script refusing to run."""
    if cache_name:
        cache_path = CACHE_DIR / cache_name
        if cache_path.exists():
            return cache_path.read_bytes()
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=TIMEOUT) as resp:
            data = resp.read()
    except (urllib.error.URLError, TimeoutError) as e:
        raise RuntimeError(f"fetching {url}: {e}") from e
    if cache_name:
        CACHE_DIR.mkdir(parents=True, exist_ok=True)
        cache_path.write_bytes(data)
    return data


def http_get_json(url, cache_name=None):
    return json.loads(http_get(url, cache_name).decode("utf-8"))


