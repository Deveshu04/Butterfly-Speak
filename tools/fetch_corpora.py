def check_license(source_key, license_name):
    """Raises unless `license_name` is one this repo may actually ship.

    THE GATE (see the module docstring). Deliberately takes the license
    VALUE, not the source key: gating on the key would let a contributor
    add a CC BY-NC row to `SOURCES` and have it written out, with its
    non-commercial license faithfully recorded in LICENSE.md, and nothing
    anywhere refusing.
    """
    if license_name not in ALLOWED_LICENSES:
        raise ValueError(
            f"refusing to write fixtures for {source_key!r}: its recorded "
            f"license {license_name!r} is not one this repo may "
            f"redistribute. Allowed: {sorted(ALLOWED_LICENSES)}. Being "
            f"listed in SOURCES is not sufficient -- the license itself is "
            f"the gate."
        )


def _validate_sources():
    """Import-time check, so a bad `SOURCES` row fails before any network
    call rather than after a fixture has already been written."""
    for key, meta in SOURCES.items():
        missing = [f for f in _REQUIRED_SOURCE_FIELDS if not meta.get(f)]
        if missing:
            raise ValueError(f"SOURCES[{key!r}] is missing required fields: {missing}")
        check_license(key, meta["license"])


_validate_sources()


def write_fixture(source_key, cases):
    """The one function allowed to write case data under tests/fixtures/.

    Refuses -- raises, writes nothing -- unless `source_key` is a key of
    `SOURCES` AND the license recorded there is in `ALLOWED_LICENSES`.
    This is the actual enforcement, not just a comment: every fetch_*
    function below funnels through this.
    """
    if source_key in BLOCKED_SOURCES:
        raise ValueError(
            f"refusing to write fixtures for {source_key!r}: this source is "
            f"on the explicit block-list. Reason: {BLOCKED_SOURCES[source_key]}"
        )
    if source_key in PENDING_SOURCES:
        raise ValueError(
            f"refusing to write fixtures for {source_key!r}: license not "
            f"yet verified. {PENDING_SOURCES[source_key]['why_excluded']}"
        )
    # Checked against the live `SOURCES` table, not the `ALLOWED_SOURCES`
    # snapshot: the snapshot is for the import-time consistency asserts,
    # and a check that read it could disagree with the table the license
    # is then read from.
    if source_key not in SOURCES:
        raise ValueError(
            f"refusing to write fixtures for {source_key!r}: not on the "
            f"license-verified allow-list {sorted(SOURCES)}. Add it to "
            f"SOURCES in this file first, with a first-party license "
            f"citation, before writing any fixture for it."
        )
    # The real gate: what the license SAYS, not what the key is called.
    check_license(source_key, SOURCES[source_key]["license"])
    if not cases:
        raise ValueError(f"{source_key}: refusing to write an empty fixture file")

    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    out_path = FIXTURES_DIR / f"{source_key}.jsonl"
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        for case in cases:
            # Insertion order, not sort_keys: matches the field order of
            # the fixture format in the module doc (id, source, kind, lang,
            # input, target[, verbatim][, tags]). JSON object key order carries no
            # semantic meaning, so this is purely for human diffing.
            f.write(json.dumps(case, ensure_ascii=False))
            f.write("\n")
    print(f"wrote {len(cases)} cases -> {out_path.relative_to(REPO_ROOT)}")
    return out_path


