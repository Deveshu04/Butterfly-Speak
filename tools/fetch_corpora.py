def write_license_md(counts=None):
    counts = counts or {}
    lines = []
    lines.append("# Fixture corpus licenses\n")
    lines.append(
        "Generated by `tools/fetch_corpora.py` -- do not hand-edit, "
        "re-run the script instead. Every file in `tests/fixtures/*.jsonl` "
        "is a ~200-case sample drawn from exactly one source below. Each "
        "license was confirmed from a first-party statement (a LICENSE "
        "file in the source's own distribution, or a license field in its "
        "own dataset card) at fetch time -- see `license_evidence` in "
        "the `SOURCES` table of `tools/fetch_corpora.py` for exactly what "
        "was checked and where.\n"
    )
    lines.append(
        "Only these licenses may be shipped from this repo: "
        + ", ".join(sorted(ALLOWED_LICENSES))
        + ". That set -- not the list of source names -- is what the fetch "
        "script actually enforces before writing a fixture.\n"
    )
    lines.append(
        "The same metadata is emitted machine-readably as "
        "`tests/fixtures/sources.json`, so a benchmark report can print "
        "each source's caveat next to its score instead of leaving it "
        "here where nobody reading a number will see it.\n"
    )
    for key, meta in SOURCES.items():
        lines.append(f"## {meta['name']} -- `{key}.jsonl`\n")
        lines.append(f"- **License:** {meta['license']} ({meta['license_url']})")
        lines.append(f"- **Evidence:** {meta['license_evidence']}")
        lines.append(f"- **Source:** {meta['url']}")
        lines.append(f"- **Revision:** {meta['revision']} ({meta['revision_kind']})")
        lines.append(f"- **Citation:** {meta['citation']}")
        lines.append(f"- **Caveat:** {meta['caveat']}")
        if key in counts:
            lines.append(f"- **Cases:** {counts[key]}")
        lines.append("")
    lines.append("## Researched but NOT included\n")
    for key, meta in PENDING_SOURCES.items():
        lines.append(f"### {meta['name']}\n")
        lines.append(f"- **Source:** {meta['url']}")
        lines.append(f"- **Claimed license:** {meta['claimed_license']}")
        lines.append(f"- **Why excluded:** {meta['why_excluded']}")
        lines.append("")
    lines.append(
        "## Never use (verified CC BY-NC / LDC-paid / punctuation-stripped "
        "-- do not add)\n"
    )
    for key, reason in sorted(BLOCKED_SOURCES.items()):
        lines.append(f"- **{key}** -- {reason}")
    lines.append("")
    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    out_path = FIXTURES_DIR / "LICENSE.md"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {out_path.relative_to(REPO_ROOT)}")


# ---------------------------------------------------------------------------
# sources.json -- the same metadata, where the harness can reach it.
#
# LICENSE.md is for a human who opens tests/fixtures/. A benchmark report
# prints numbers somewhere else entirely, and a caveat that only exists in
# a Markdown file nobody has open while reading a score is not doing its
# job -- "LibriSpeech-PC is read speech, treat it as a regression guard,
# not a target" has to be printable BESIDE the LibriSpeech-PC number.
# ---------------------------------------------------------------------------


def write_sources_json(sampled_by_source):
    entries = {}
    for key, meta in SOURCES.items():
        cases = sampled_by_source.get(key)
        if cases is None:
            # A source whose fetch failed this run: its metadata still
            # belongs here, but claiming a case count would be a lie.
            counts = None
        else:
            counts = {
                "cases": len(cases),
                "kinds": sorted({c["kind"] for c in cases}),
                "langs": sorted({c["lang"] for c in cases}),
                "tags": {
                    tag: sum(1 for c in cases if tag in c.get("tags", []))
                    for tag in sorted(
                        {t for c in cases for t in c.get("tags", [])}
                    )
                },
            }
        entries[key] = {
            "name": meta["name"],
            "url": meta["url"],
            "license": meta["license"],
            "license_url": meta["license_url"],
            "license_evidence": meta["license_evidence"],
            "citation": meta["citation"],
            "caveat": meta["caveat"],
            "revision": meta["revision"],
            "revision_kind": meta["revision_kind"],
            "fixture": f"{key}.jsonl",
            **({} if counts is None else counts),
        }
    doc = {
        "generated_by": "tools/fetch_corpora.py",
        "methodology": (
            "AssemblyAI Universal-2-TF (arXiv:2501.05948): `target` is text "
            "that already has correct punctuation and casing; `input` is "
            "the same text lowercased and stripped of punctuation, "
            "simulating raw ASR output. Score = how well the formatter "
            "restores `target` from `input`."
        ),
        "allowed_licenses": sorted(ALLOWED_LICENSES),
        "sample_seed": SAMPLE_SEED,
        "target_sample_size": TARGET_SAMPLE_SIZE,
        "sources": entries,
    }
    FIXTURES_DIR.mkdir(parents=True, exist_ok=True)
    out_path = FIXTURES_DIR / "sources.json"
    out_path.write_text(
        json.dumps(doc, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {out_path.relative_to(REPO_ROOT)}")


